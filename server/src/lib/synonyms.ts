/**
 * 常见食材的俗称 / 别名分组，供菜谱搜索做联想：
 * 搜「西红柿」也能找到配料写「番茄」的菜，反之亦然。
 *
 * 匹配规则：只要关键词里**包含**组内任一别名，就把整组词都加入搜索条件
 * （「西红柿炒蛋」会连带「番茄」、「番茄鸡蛋」会连带「西红柿」和「蛋」）。
 * 联想只会扩大结果（OR 条件），不会收窄，因此宁可多联想也不会漏掉原词。
 * 收录标准：叫法确实存在歧义或地域差；同一种食材的不同部位 / 品种（如鸡翅之于鸡肉）
 * 只在家人大概率混用时才收进来。
 */
