/** 把一个搜索词展开成「原词 + 命中别名组的全部别名」；没有命中就原样返回 */
export function expandSearchTerms(term: string): string[] {
  if (!term.trim()) return [];
  const result = new Set<string>([term]);
  for (const group of SYNONYM_GROUPS) {
    if (group.some((alias) => term.includes(alias))) {
      group.forEach((alias) => result.add(alias));
    }
  }
  return [...result];
}

/**
 * 取一个词的别名组，**只认「整个词就是组内某个别名」**（`group.includes`），
 * 刻意与上面 expandSearchTerms 的包含匹配区分开。
 *
 * 为什么要两个口径：搜索里「沙姜」包含「姜」而把生姜一起联想出来是有益的（OR 条件，
 * 多给几个结果无所谓）；但**身份归并**用包含匹配就会把「沙姜」并成「生姜」——
 * 沙姜是另一种食材，并错了采购清单会让人买错东西、AI 填的营养也会被丢掉。
 * 所以判定「是不是同一个食材」只能走这个整词版本。
 */
export function synonymGroupOf(term: string): string[] | null {
  const trimmed = term.trim();
  if (!trimmed) return null;
  return SYNONYM_GROUPS.find((group) => group.includes(trimmed)) ?? null;
}
